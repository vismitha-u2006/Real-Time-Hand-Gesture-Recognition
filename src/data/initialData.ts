function createSeedCapture(
  id: string,
  capturedAt: string,
  sessionCode: string,
  gesture: CapturedFrame['gesture'],
  gestureLabel: string,
  diagnosticState: CapturedFrame['diagnosticState'],
  fps: number,
  latencyMs: number,
  confidence: number,
  modelId: CapturedFrame['modelId'],
  backend: CapturedFrame['backend'],
  notes: string,
  yawRad: number,
  pitchRad: number
): CapturedFrame {
  const landmarks = computeHandLandmarks({
    gesture,
    pinchBlend: gesture === 'precision_pinch' ? 1 : 0,
    centerX: 0.5,
    centerY: 0.54,
    yawRad,
    pitchRad,
    depthScale: 1.0,
    jitterSigma: 0.0008,
    diagnosticState,
    timeSec: 4.2,
  });

  return {
    id,
    capturedAt,
    sessionCode,
    gesture,
    gestureLabel,
    diagnosticState,
    fps,
    latencyMs,
    confidence,
    pinchApertureMm: Number(computePinchApertureMm(landmarks).toFixed(1)),
    modelId,
    backend,
    notes,
    landmarks,
  };
}

